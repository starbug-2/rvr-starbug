"""Summarise run_starbug2.sh output into OUT/results.md and
OUT/<bench>/hot_blocks.md."""

import glob
import json
import math
import os
import re
import subprocess
import sys

CODES = [("o2", "-O2"), ("unroll", "-O2 -funroll-loops")]
WIDTHS = [("w4", "4-way"), ("w8", "8-way"), ("w8m4", "8-way, MUL on 4 lanes")]
FEATS = [("base", "base"), ("load", "+load"), ("br0", "+branch (lane 0)"),
         ("brown", "+branch (own lane)"), ("load_br0", "+load +branch (lane 0)"),
         ("load_brown", "+load +branch (own lane)")]
SIZE = os.environ.get("RVSIZE", os.path.expanduser("~/riscv/rv32/bin/riscv32-unknown-elf-size"))


def kv(path):
  try:
    return dict(re.findall(r"^(\w+)=(\S+)", open(path).read(), re.M))
  except OSError:
    return {}


def proto(d):
  vals, name = {}, None
  for f in glob.glob(os.path.join(d, "*.proto")):
    for line in open(f):
      m = re.search(r'name: "(\w+)"', line)
      if m:
        name = m.group(1)
        continue
      m = re.search(r"uint64_value: (\d+)", line)
      if m and name:
        vals[name] = int(m.group(1))
        name = None
  return vals


def run(cfgdir, tag):
  d = os.path.join(cfgdir, "runs", tag)
  r = kv(os.path.join(d, "stdout.txt"))
  r["kc"] = int(r.get("kernel_cycles", 0) or 0)
  r["p"] = proto(d)
  return r


def text_bytes(cfgdir):
  objs = sorted(glob.glob(os.path.join(cfgdir, "[0-9]*.o")))
  if not objs:
    return 0
  out = subprocess.run([SIZE] + objs, capture_output=True, text=True).stdout
  return sum(int(l.split()[0]) for l in out.splitlines()[1:] if l.strip())


def sched(cfgdir):
  blocks = {}
  for f in sorted(glob.glob(os.path.join(cfgdir, "*.sched.json"))):
    for blk in json.load(open(f))["blocks"]:
      blocks[blk["label"]] = blk
  return blocks


def x(a, b):
  return a / b if a and b else 0.0


def geo(v):
  v = [t for t in v if t > 0]
  return math.exp(sum(map(math.log, v)) / len(v)) if v else 0.0


def load(out, b, code):
  base = os.path.join(out, b, code)
  D = {"bench": b, "code": code, "dir": base, "scalar": run(os.path.join(base, "scalar"), "ideal"),
       "hint": run(os.path.join(base, "hint_R0_al"), "ideal"), "cfg": {}}
  D["hint"]["check"] = open(os.path.join(base, "hint_R0_al", "rule_check.txt")).read() + \
      open(os.path.join(base, "hint_R0", "rule_check.txt")).read()
  D["scalar"]["text"] = text_bytes(os.path.join(base, "scalar"))
  hist = {}
  for line in open(os.path.join(base, "scalar", "pc_histogram.txt")):
    a, c = line.split()
    hist[int(a, 16)] = int(c)
  labels = {}
  for line in open(os.path.join(base, "scalar", "block_labels.txt")):
    a, _t, n = line.split()
    labels[n] = int(a, 16)
  D["counts"] = {n: hist.get(a, 0) for n, a in labels.items()}
  D["sched_scalar"] = sched(os.path.join(base, "scalar"))
  for w, _ in WIDTHS:
    for f, _ in FEATS:
     for suffix in ("", "_al"):
      c = "%s_%s%s" % (w, f, suffix)
      cd = os.path.join(base, c)
      if not os.path.isdir(cd):
        continue
      e = {t: run(cd, t) for t in ("ideal", "ideal_nofetch", "interleave", "split")}
      e["split_placed"] = run(os.path.join(cd, "placed"), "split_placed")
      e["check"] = open(os.path.join(cd, "rule_check.txt")).read().strip()
      e["text"] = text_bytes(cd)
      e["sched"] = sched(cd)
      D["cfg"][c] = e
  return D


def predicted(D, blocks):
  total = D["scalar"]["p"].get("num_instructions", 0)
  for n, blk in blocks.items():
    total -= D["counts"].get(n, 0) * (len(blk["insns"]) - len(blk["bundles"]))
  return total


def all_ok(D):
  ok = D["scalar"].get("verify") == "PASS" and D["hint"].get("verify") == "PASS"
  checks = D["hint"]["check"].count(" 0 break") == 2
  for e in D["cfg"].values():
    for t in ("ideal", "ideal_nofetch", "interleave", "split", "split_placed"):
      if e[t].get("verify") and e[t]["verify"] != "PASS":
        ok = False
    if e["ideal"].get("verify") != "PASS":
      ok = False
    checks = checks and " 0 break the rules" in e["check"]
  return ok, checks


def results_md(data, benches):
  L = ["# STARBUG2 experiment: custom-0 execute-packet header\n",
       "Generated by `benchmarks/explore/run_starbug2.sh`. Cycles are MPACT cycles for the timed "
       "`benchmark()` region: one per packet or scalar instruction, plus one per packet that "
       "spans a 64-byte I-cache line and one per bank-conflict stall. Speedups are over the "
       "scalar build of the same code. Unless stated, builds use the fetch-aware layout "
       "(small loops start on a 64-byte line) with the fetch model on. The STARBUG1 hint "
       "baseline uses the same layout and line size; its crossing bundles run scalar, as "
       "in last year's RTL (N members cost N extra cycles).\n"]
  L.append("## 0. Correctness and checks\n")
  L.append("| benchmark | code | all runs verify | every packet passes rule_check2 / hint R0 rule_check |")
  L.append("|---|---|---|---|")
  for b in benches:
    for code, cname in CODES:
      D = data.get((b, code))
      if D:
        ok, ch = all_ok(D)
        L.append("| %s | %s | %s | %s |" % (b, cname, "PASS" if ok else "**FAIL**", "pass" if ch else "**FAIL**"))

  def spd(D, cfg, tag="ideal"):
    e = D["cfg"].get(cfg)
    return x(D["scalar"]["kc"], e[tag]["kc"]) if e and e[tag]["kc"] else 0.0

  for code, cname in CODES:
    L.append("\n## 1%s. Speedup over scalar, `%s` (ideal memory)\n" % ("a" if code == "o2" else "b", cname))
    for w, wname in WIDTHS:
      L.append("### %s\n" % wname)
      L.append("| benchmark | scalar cycles | hint R0 (STARBUG1) | " + " | ".join(n for _, n in FEATS) + " |")
      L.append("|---|---|---|" + "---|" * len(FEATS))
      cols, hints = {f: [] for f, _ in FEATS}, []
      for b in benches:
        D = data.get((b, code))
        if not D:
          continue
        s = D["scalar"]["kc"]
        h = x(s, D["hint"]["kc"])
        hints.append(h)
        cells = []
        for f, _ in FEATS:
          v = spd(D, "%s_%s_al" % (w, f))
          cols[f].append(v)
          cells.append("%.2fx" % v)
        L.append("| %s | %d | %.2fx | %s |" % (b, s, h, " | ".join(cells)))
      L.append("| **geomean** | | %.2fx | %s |" % (geo(hints), " | ".join("**%.2fx**" % geo(cols[f]) for f, _ in FEATS)))
      L.append("")

  L.append("## 2. 4-way vs 8-way and the fetch crossing\n")
  L.append("Speedup over scalar for three fetch assumptions: *naive* = packets placed wherever "
           "the code falls, crossing costs a cycle; *aligned* = loops start on a 64-byte line, "
           "crossing costs a cycle; *no penalty* = crossing is free (the upper bound). "
           "*cross* = share of executed packets that span a line. *code* = `.text` growth of "
           "the benchmark's own code over scalar (aligned layout, includes the padding).\n")
  for code, cname in CODES:
    L.append("### `%s`\n" % cname)
    L.append("| benchmark | config | width | naive (cross) | aligned (cross) | no penalty | code |")
    L.append("|---|---|---|---|---|---|---|")
    geos = {}
    for b in benches:
      D = data.get((b, code))
      if not D:
        continue
      for f in ("base", "load_brown"):
        for w in ("w4", "w8"):
          cells = []
          for cfg in ("%s_%s" % (w, f), "%s_%s_al" % (w, f)):
            e = D["cfg"][cfg]
            pk = e["ideal"]["p"].get("num_StarbugHdr", 0)
            cr = e["ideal"]["p"].get("num_packet_line_crossings", 0)
            v = spd(D, cfg)
            geos.setdefault((f, w, cfg.endswith("_al")), []).append(v)
            cells.append("%.2fx (%.0f%%)" % (v, 100.0 * cr / pk if pk else 0))
          v = spd(D, "%s_%s_al" % (w, f), "ideal_nofetch")
          geos.setdefault((f, w, "nofetch"), []).append(v)
          cells.append("%.2fx" % v)
          e = D["cfg"]["%s_%s_al" % (w, f)]
          cells.append("%+.0f%%" % (100.0 * (e["text"] - D["scalar"]["text"]) / D["scalar"]["text"]))
          L.append("| %s | %s | %s | %s |" % (b, dict(FEATS)[f], w[1:] + "-way", " | ".join(cells)))
    for f in ("base", "load_brown"):
      for w in ("w4", "w8"):
        L.append("| **geomean** | %s | %s | %.2fx | %.2fx | %.2fx | |" % (
            dict(FEATS)[f], w[1:] + "-way", geo(geos[(f, w, False)]), geo(geos[(f, w, True)]),
            geo(geos[(f, w, "nofetch")])))
    L.append("")

  L.append("## 3. Second load port on two banks (`+load +branch (own lane)`)\n")
  L.append("Speedup over scalar; in brackets the share of two-load packets whose loads hit the same bank.\n")
  for code, cname in CODES:
    L.append("### `%s`\n" % cname)
    L.append("| benchmark | width | no extra load | ideal | word interleave | upper/lower | upper/lower + placement |")
    L.append("|---|---|---|---|---|---|---|")
    for b in benches:
      D = data.get((b, code))
      if not D:
        continue
      s = D["scalar"]["kc"]
      for w in ("w4", "w8"):
        e = D["cfg"].get(w + "_load_brown_al")
        cells = ["%.2fx" % spd(D, w + "_brown_al"), "%.2fx" % spd(D, w + "_load_brown_al")]
        for t in ("interleave", "split", "split_placed"):
          p = e[t]["p"]
          pairs, conf = p.get("num_multi_mem_bundles", 0), p.get("num_bank_conflicts", 0)
          cells.append("%.2fx (%.0f%%)" % (x(s, e[t]["kc"]), 100.0 * conf / pairs if pairs else 0)
                       if e[t]["kc"] else "n/a")
        L.append("| %s | %s | %s |" % (b, w[1:] + "-way", " | ".join(cells)))
    L.append("")

  L.append("## 4. 8-way with multipliers on only 4 lanes\n")
  L.append("| benchmark | code | base: 8 MUL / 4 MUL | +load +branch (own): 8 MUL / 4 MUL |")
  L.append("|---|---|---|---|")
  for b in benches:
    for code, cname in CODES:
      D = data.get((b, code))
      if D:
        L.append("| %s | %s | %.3fx / %.3fx | %.3fx / %.3fx |" % (
            b, cname, *[spd(D, k) for k in ("w8_base_al", "w8m4_base_al", "w8_load_brown_al", "w8m4_load_brown_al")]))
  L.append("")

  L.append("## 5. Self-check: bundler accounting vs simulator (naive layout)\n")
  L.append("Whole-program cycles predicted from block counts x packets per block, against the "
           "simulator's `num_cycles` (ideal memory, fetch model off). Small positive differences "
           "come from the assembler rewriting out-of-range branches.\n")
  L.append("| benchmark | code | configurations matching exactly | largest difference |")
  L.append("|---|---|---|---|")
  for b in benches:
    for code, cname in CODES:
      D = data.get((b, code))
      if not D:
        continue
      exact = worst = total = 0
      for c, e in D["cfg"].items():
        if c.endswith("_al"):
          continue
        diff = e["ideal_nofetch"]["p"].get("num_cycles", 0) - predicted(D, e["sched"])
        exact += diff == 0
        worst = max(worst, abs(diff))
        total += 1
      L.append("| %s | %s | %d / %d | %d |" % (b, cname, exact, total, worst))
  return "\n".join(L) + "\n"


def hot_md(Ds, b):
  L = ["# %s: hottest blocks under STARBUG2\n" % b,
       "Packets per execution for the hottest blocks. The full bundled assembly is in "
       "`<code>/<config>/<file>.s` (search for the label).\n"]
  for D in Ds:
    total = D["scalar"]["p"].get("num_instructions", 1)
    blocks = D["sched_scalar"]
    ranked = sorted(blocks, key=lambda n: -D["counts"].get(n, 0) * len(blocks[n]["insns"]))[:4]
    L.append("## `%s`\n" % dict(CODES)[D["code"]])
    for n in ranked:
      c = D["counts"].get(n, 0)
      if not c:
        continue
      blk = blocks[n]
      L.append("### `%s` in `%s()`: %d executions, %.1f%% of instructions, %d instructions\n" % (
          n, blk["function"], c, 100.0 * c * len(blk["insns"]) / total, len(blk["insns"])))
      line = ["scalar %d" % len(blk["insns"])]
      for cfg in ("w4_base", "w4_load_brown", "w8_base", "w8_load_brown"):
        e = D["cfg"].get(cfg)
        if e and n in e["sched"]:
          line.append("%s %d" % (cfg, len(e["sched"][n]["bundles"])))
      L.append("Packets per execution: " + ", ".join(line) + ".\n")
      if len(blk["insns"]) > 40:
        continue
      for cfg in ("w4_load_brown", "w8_load_brown"):
        e = D["cfg"].get(cfg)
        if not e or n not in e["sched"]:
          continue
        sb = e["sched"][n]
        L.append("**%s**\n```" % cfg)
        for k, pk in enumerate(sb["bundles"]):
          L.append("p%-2d %s" % (k, "  |  ".join(sb["insns"][i] for i in pk)))
        L.append("```")
        L.append("<details><summary>why</summary>\n")
        for k, pk in enumerate(sb["bundles"]):
          for i in pk:
            L.append("- p%d `%s`: %s" % (k, sb["insns"][i], sb["reasons"][i]))
        L.append("\n</details>\n")
  return "\n".join(L)


def main():
  out, benches = sys.argv[1], sys.argv[2:]
  data = {}
  for b in benches:
    for code, _ in CODES:
      try:
        data[(b, code)] = load(out, b, code)
      except OSError as e:
        print("%s %s: missing data (%s)" % (b, code, e), file=sys.stderr)
    Ds = [data[(b, c)] for c, _ in CODES if (b, c) in data]
    if Ds:
      open(os.path.join(out, b, "hot_blocks.md"), "w").write(hot_md(Ds, b))
  md = results_md(data, benches)
  open(os.path.join(out, "results.md"), "w").write(md)
  print(md)


if __name__ == "__main__":
  main()
