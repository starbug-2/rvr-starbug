"""Summarise run_phase2.sh output into OUT/results.md."""

import glob
import json
import os
import sys

import report2 as r2

CODES = [("o2", "-O2"), ("unroll", "-O2 -funroll-loops")]
WIDTHS = [("w4", "4-way"), ("w8", "8-way")]
FEATS = [("load_brown", "+load +branch (own lane)"), ("base", "base")]
VARS = [("none", "phase 1"), ("ai", "+autoinc"), ("pA", "+pred A"), ("pB", "+pred B"),
        ("pA_all", "+pred A forced"), ("pA_ai", "+pred A +autoinc"), ("pB_ai", "+pred B +autoinc")]


def stats(cfgdir):
  tot = {}
  for f in glob.glob(os.path.join(cfgdir, "*.sched.json")):
    for k, v in json.load(open(f)).get("transform_stats", {}).items():
      tot[k] = tot.get(k, 0) + v
  return tot


def load(out, b, code):
  base = os.path.join(out, b, code)
  D = {"scalar": r2.run(os.path.join(base, "scalar"), "ideal"),
       "scalar_fixed": r2.run(os.path.join(base, "scalar_fixed"), "ideal"),
       "text": r2.text_bytes(os.path.join(base, "scalar")), "cfg": {}}
  for w, _ in WIDTHS:
    for f, _ in FEATS:
      for v, _ in VARS:
        c = "%s_%s_%s" % (w, f, v)
        cd = os.path.join(base, c)
        if os.path.isdir(cd):
          D["cfg"][c] = {"ideal": r2.run(cd, "ideal"), "nofetch": r2.run(cd, "ideal_nofetch"),
                         "check": open(os.path.join(cd, "rule_check.txt")).read(),
                         "stats": stats(cd), "text": r2.text_bytes(cd)}
  return D


def main():
  out, benches = sys.argv[1], sys.argv[2:]
  data = {(b, c): load(out, b, c) for b in benches for c, _ in CODES
          if os.path.isdir(os.path.join(out, b, c))}
  L = ["# STARBUG2 phase 2: predication and post-increment\n",
       "Generated by `benchmarks/explore/run_phase2.sh`. Speedups over the scalar `-O2` build "
       "(the setup B scalar build reserves s8-s11, priced in section 2). Fetch-aware layout, "
       "64-byte fetch model, ideal memory.\n",
       "*pred A*: predicates in x9-x15 (s1, a0-a5) as specified, used where liveness shows them "
       "free. *pred B*: `creg` remapped to s8-s11, reserved in all compiled code. Conversions are "
       "profile-guided: kept only if, weighted by the scalar run's execution counts, they do not "
       "cost more issue slots. *forced*: convert every candidate regardless.\n"]
  L.append("## 0. Correctness and checks\n")
  L.append("| benchmark | code | all runs verify | all packets pass rule_check2 |")
  L.append("|---|---|---|---|")
  for b in benches:
    for code, cname in CODES:
      D = data.get((b, code))
      if not D:
        continue
      ok = D["scalar"].get("verify") == "PASS" and D["scalar_fixed"].get("verify") == "PASS"
      ch = True
      for e in D["cfg"].values():
        ok = ok and e["ideal"].get("verify") == "PASS" and e["nofetch"].get("verify") == "PASS"
        ch = ch and " 0 break the rules" in e["check"]
      L.append("| %s | %s | %s | %s |" % (b, cname, "PASS" if ok else "**FAIL**", "pass" if ch else "**FAIL**"))

  L.append("\n## 1. What the transforms found (4-way, +load +branch)\n")
  L.append("Static counts over the benchmark's own code. Branches: conditional branches seen; "
           "converted by shape; rejected by reason. Fused: pointer increments folded into a "
           "post-increment access.\n")
  L.append("| benchmark | code | setup | branches | if-then | if-then-else | guard chain | no shape | "
           "arm too long | no free pred. reg | not profitable | fused (autoinc) |")
  L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
  keys = ["branches", "if-then", "if-then-else", "guard chain", "no shape", "arm too long or empty",
          "no free predicate register", "not profitable"]  # "needs branch in packet" only on base
  for b in benches:
    for code, cname in CODES:
      D = data.get((b, code))
      if not D:
        continue
      for setup in ("pA_ai", "pB_ai"):
        st = D["cfg"]["w4_load_brown_" + setup]["stats"]
        L.append("| %s | %s | %s | %s | %d |" % (b, cname, "A" if setup == "pA_ai" else "B",
                                             " | ".join(str(st.get(k, 0)) for k in keys), st.get("fused", 0)))

  L.append("\n## 2. Cost of reserving s8-s11 (setup B)\n")
  L.append("| benchmark | code | scalar cycles | scalar with s8-s11 reserved | change |")
  L.append("|---|---|---|---|---|")
  for b in benches:
    for code, cname in CODES:
      D = data.get((b, code))
      if D:
        s, sf = D["scalar"]["kc"], D["scalar_fixed"]["kc"]
        L.append("| %s | %s | %d | %d | %+.2f%% |" % (b, cname, s, sf, 100.0 * (sf - s) / s if s else 0))

  for code, cname in CODES:
    for f, fname in FEATS:
      L.append("\n## 3. Speedup over scalar: `%s`, %s\n" % (cname, fname))
      for w, wname in WIDTHS:
        L.append("### %s\n" % wname)
        L.append("| benchmark | " + " | ".join(n for _, n in VARS) + " |")
        L.append("|---|" + "---|" * len(VARS))
        cols = {v: [] for v, _ in VARS}
        for b in benches:
          D = data.get((b, code))
          if not D:
            continue
          s = D["scalar"]["kc"]
          cells = []
          for v, _ in VARS:
            e = D["cfg"].get("%s_%s_%s" % (w, f, v))
            x = r2.x(s, e["ideal"]["kc"]) if e else 0
            cols[v].append(x)
            cells.append("%.3fx" % x)
          L.append("| %s | %s |" % (b, " | ".join(cells)))
        L.append("| **geomean** | %s |" % " | ".join("**%.3fx**" % r2.geo(cols[v]) for v, _ in VARS))
        L.append("")

  L.append("## 3c. Geomean speedup without the fetch penalty\n")
  L.append("Same builds, crossing charged nothing: isolates the scheduling effect of each "
           "feature from its effect on code size and line crossings.\n")
  L.append("| code | machine | width | " + " | ".join(n for _, n in VARS) + " |")
  L.append("|---|---|---|" + "---|" * len(VARS))
  for code, cname in CODES:
    for f, fname in FEATS:
      for w, wname in WIDTHS:
        cols = {v: [] for v, _ in VARS}
        for b in benches:
          D = data.get((b, code))
          if not D:
            continue
          for v, _ in VARS:
            e = D["cfg"].get("%s_%s_%s" % (w, f, v))
            cols[v].append(r2.x(D["scalar"]["kc"], e["nofetch"]["kc"]) if e else 0)
        L.append("| %s | %s | %s | %s |" % (cname, fname, wname,
                                           " | ".join("%.3fx" % r2.geo(cols[v]) for v, _ in VARS)))
  L.append("")

  L.append("## 4. Post-increment: code size and fetch crossings (4-way, +load +branch)\n")
  L.append("| benchmark | code | code bytes: phase 1 / +autoinc | cycles without fetch penalty: phase 1 / +autoinc "
           "| cross % of packets: phase 1 / +autoinc |")
  L.append("|---|---|---|---|---|")
  for b in benches:
    for code, cname in CODES:
      D = data.get((b, code))
      if not D:
        continue
      e0, e1 = D["cfg"]["w4_load_brown_none"], D["cfg"]["w4_load_brown_ai"]

      def cross(e):
        p = e["ideal"]["p"]
        pk = p.get("num_StarbugHdr", 0)
        return 100.0 * p.get("num_packet_line_crossings", 0) / pk if pk else 0
      L.append("| %s | %s | %d / %d (%+.1f%%) | %d / %d (%+.1f%%) | %.0f%% / %.0f%% |" % (
          b, cname, e0["text"], e1["text"], 100.0 * (e1["text"] - e0["text"]) / e0["text"],
          e0["nofetch"]["kc"], e1["nofetch"]["kc"],
          100.0 * (e1["nofetch"]["kc"] - e0["nofetch"]["kc"]) / e0["nofetch"]["kc"],
          cross(e0), cross(e1)))
  md = "\n".join(L) + "\n"
  open(os.path.join(out, "results.md"), "w").write(md)
  print(md)


if __name__ == "__main__":
  main()
