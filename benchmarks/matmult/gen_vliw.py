# Emit the hand-scheduled matmult kernels:
#
#   matmult_vliw.S      the STARBUG schedule, with c.li x0,N bundle hints
#   matmult_unrolled.S  the identical instruction stream with the hints removed
#
# The two files differ only in the hint lines, so (unrolled vs scalar C) is what
# unrolling buys and (vliw vs unrolled) is what bundling buys.
#
# Schedule. The k loop is fully unrolled, so A and B are addressed with
# immediate offsets (A[i][k] = 4k(a0), B[k][j] = 80k(a1)) and need no pointer
# bumps. Each dot product is software-pipelined across bundles:
#
#   t = 2m   : lane0 lw A[i][m]   | lane1 mul p, A[i][m-1], B[m-1][j]
#   t = 2m+1 : lane0 lw B[m][j]   | lane1 add acc, acc, p    (p from mul m-1)
#
# A and B values rotate through two registers each, so no bundle has a RAW,
# WAR or WAW pair. Every bundle obeys the STARBUG RTL contract (paper Table 1,
# starbug-llvm tools/starbug_bundle_check.py):
#   - 1 <= N <= 4
#   - loads/stores/branches only in lane 0 (the first payload slot), and at
#     most one memory op per bundle
#   - no intra-bundle register dependences
#   - branches are never bundled (same policy as the starbug-llvm packetizer),
#     which sidesteps the unresolved "taken lane-0 branch + worker ops" case
#
# usage: python3 gen_vliw.py   (writes both files next to this script)

import os

N = 20                 # must match MATMULT_N in matmult.h
ROW_BYTES = 4 * N      # 80
assert 4 * (N - 1) < 2048 and ROW_BYTES * (N - 1) < 2048  # fit in imm12

A_REG = ["t0", "t1"]   # A[i][k], rotating
B_REG = ["t2", "t3"]   # B[k][j], rotating
PROD = "t4"
ACC = "t5"
# a0 = &A[i][0], a1 = &B[0][j], a2 = &Res[i][j] (+4 once the element's
# loads are done), a3 = &A[N][0] (row-loop end), a4 = &B[0][N] (col-loop end)


def element_schedule():
  """List of bundles (each a list of instruction strings) for one Res[i][j].

  Pair m is loaded at t=2m (A) and t=2m+1 (B), multiplied at t=2m+2 and
  accumulated at t=2m+3, so step m's bundles carry the multiply and the add
  for pair m-1.
  """
  sched = []
  for m in range(N):
    even = ["lw\t%s,%d(a0)" % (A_REG[m % 2], 4 * m)]
    odd = ["lw\t%s,%d(a1)" % (B_REG[m % 2], ROW_BYTES * m)]
    if m >= 1:
      p = (m - 1) % 2
      even.append("mul\t%s,%s,%s" % (PROD, A_REG[p], B_REG[p]))
      odd.append("mv\t%s,%s" % (ACC, PROD) if m == 1
                 else "add\t%s,%s,%s" % (ACC, ACC, PROD))
    sched += [even, odd]
  # drain: multiply the last pair, and bump the pointers now that every load
  # for this element has issued
  p = (N - 1) % 2
  sched.append(["mul\t%s,%s,%s" % (PROD, A_REG[p], B_REG[p]),
                "addi\ta1,a1,4", "addi\ta2,a2,4"])
  return sched


def emit(f, hints):
  w = f.write
  w("# GENERATED by gen_vliw.py -- do not edit by hand.\n")
  w("# %s\n" % ("STARBUG-bundled matmult (with bundle hints)." if hints else
                "Same instruction stream as matmult_vliw.S, hints removed."))
  w('\t.file\t"%s"\n' % ("matmult_vliw.S" if hints else "matmult_unrolled.S"))
  w("\t.option nopic\n")
  w('\t.attribute arch, "rv32i2p1_m2p0_a2p1_c2p0"\n')
  w("\t.text\n\t.align\t2\n\t.globl\tmatmult\n\t.type\tmatmult, @function\n")
  w("# void matmult(const int32_t *A, const int32_t *B, int32_t *Res)\n")
  w("matmult:\n")

  def bundle(insns, comment=""):
    if hints and len(insns) > 1:
      w("\tc.li\tx0,%d%s\n" % (len(insns), ("\t\t# " + comment) if comment else ""))
    elif comment:
      w("\t# %s\n" % comment)
    for ins in insns:
      w("\t%s\n" % ins)

  bundle(["addi\ta3,a0,%d" % (ROW_BYTES * N), "addi\ta4,a1,%d" % ROW_BYTES],
         "row-loop and col-loop end pointers")
  w(".Lcol:\t\t\t\t# one Res[i][j] per iteration\n")
  for t, b in enumerate(element_schedule()):
    bundle(b, "t=%d" % t)
  w("\tadd\t%s,%s,%s\t\t# accumulate the last product\n" % (ACC, ACC, PROD))
  w("\tsw\t%s,-4(a2)\t\t# Res[i][j] (a2 was already bumped)\n" % ACC)
  w("\tbne\ta1,a4,.Lcol\n")
  bundle(["addi\ta0,a0,%d" % ROW_BYTES, "addi\ta1,a1,-%d" % ROW_BYTES],
         "next row of A, back to column 0 of B")
  w("\tbne\ta0,a3,.Lcol\n")
  w("\tret\n")
  w("\t.size\tmatmult, .-matmult\n")


here = os.path.dirname(os.path.abspath(__file__))
for name, hints in (("matmult_vliw.S", True), ("matmult_unrolled.S", False)):
  with open(os.path.join(here, name), "w") as f:
    emit(f, hints)
  print("wrote", name)
